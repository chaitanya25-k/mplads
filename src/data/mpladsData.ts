export function computeNationalStats(mps: MPRecord[], works: WorkItem[], anomalies: AnomalyAlert[], calamities: CalamityRecord[]): NationalStats {
  const totalAllocatedLimit = mps.reduce((acc, mp) => acc + mp.allocatedAmount, 0);
  const totalExpenditure = mps.reduce((acc, mp) => acc + mp.expenditureAmount, 0);
  const avgUtil = totalAllocatedLimit > 0 ? (totalExpenditure / totalAllocatedLimit) * 100 : 0;
  
  const completedWorks = works.filter(w => w.status === 'PHYSICAL_COMPLETED' || w.status === 'UC_SUBMITTED').length;
  const underExecutionWorks = works.filter(w => w.status === 'UNDER_EXECUTION' || w.status === 'MILESTONE_PAID').length;
  const stalledWorks = works.filter(w => w.status === 'STALLED').length;
  
  const criticalRedFlags = anomalies.filter(a => a.severity === 'CRITICAL' && a.status !== 'RESOLVED_JUSTIFIED').length;
  const highRiskWorksValue = anomalies
    .filter(a => a.severity === 'CRITICAL' || a.severity === 'HIGH')
    .reduce((acc, a) => {
      const match = works.find(w => w.id === a.workId);
      return acc + (match ? match.sanctionedCost : 0);
    }, 0);

  const duplicateWorksCaught = anomalies.filter(a => a.category === 'DUPLICATE_WORK').length;
  const calamityFundsApproved = calamities.reduce((acc, c) => acc + c.consentAmount, 0);

  return {
    totalAllocatedLimit,
    totalExpenditure,
    averageUtilizationRate: avgUtil,
    totalMPs: mps.length,
    totalWorks: works.length,
    completedWorks,
    underExecutionWorks,
    stalledWorks,
    totalAnomaliesDetected: anomalies.length,
    criticalRedFlags,
    highRiskExposureAmount: highRiskWorksValue,
    potentialSavingsPrevented: highRiskWorksValue * 0.42, // Estimated fraud / overrun recovery
    duplicateWorksCaught,
    calamityFundsApproved
  };
}

export function generateCompleteMPList(): MPRecord[] {
  return RAW_MP_DATA.map((raw, idx) => {
    // Generate realistic expenditure, works count and risk scores based on tenure and known anomalies
    const seed = (idx * 37) % 100;
    const isSpecialCase = raw.name.includes("Medha") || raw.name.includes("Dinesh") || raw.name.includes("Ashok") || raw.name.includes("Bhim");
    
    let utilPercent = seed < 20 ? (45 + seed) : seed > 80 ? 88 + (seed % 10) : 60 + (seed % 25);
    if (raw.tenure.includes("2026-2032") || raw.tenure.includes("2026-32")) {
      utilPercent = 8 + (seed % 15); // Newly elected
    }
    if (isSpecialCase) {
      utilPercent = 78;
    }

    const expAmount = Number(((raw.allocatedAmount * utilPercent) / 100).toFixed(2));
    const unspent = Number((raw.allocatedAmount - expAmount).toFixed(2));
    const worksRec = Math.max(4, Math.round(raw.allocatedAmount / 12000000));
    const worksSanc = Math.round(worksRec * 0.85);
    const worksComp = Math.round(worksSanc * (utilPercent / 100));

    let riskScore = isSpecialCase ? 82 + (idx % 12) : 15 + (seed % 35);
    let anomalyCount = isSpecialCase ? 2 + (idx % 3) : seed > 75 ? 1 : 0;

    return {
      srNo: raw.srNo,
      state: raw.state,
      name: raw.name,
      tenure: raw.tenure,
      type: raw.type as 'Elected MP' | 'Nominated MP',
      allocatedAmount: raw.allocatedAmount,
      sanctionedAmount: Number((raw.allocatedAmount * 0.92).toFixed(2)),
      expenditureAmount: expAmount,
      unspentBalance: unspent,
      utilizationRate: Number(utilPercent.toFixed(1)),
      worksRecommended: worksRec,
      worksSanctioned: worksSanc,
      worksCompleted: worksComp,
      riskScore,
      anomalyCount,
      scPercentage: 16.5 + ((idx % 7) - 3),
      stPercentage: 8.2 + ((idx % 5) - 2)
    };
  });
}
