export function computeSpendingTrustSummary(spendings: SpendingRecord[]): SpendingTrustSummary {
  const totalCount = spendings.length;
  const totalValue = spendings.reduce((acc, s) => acc + s.disbursedAmount, 0);
  const avgTrust = totalCount > 0 
    ? Number((spendings.reduce((acc, s) => acc + s.trustScore, 0) / totalCount).toFixed(1)) 
    : 0;

  const highTrust = spendings.filter(s => s.trustScore >= 85).length;
  const moderateTrust = spendings.filter(s => s.trustScore >= 50 && s.trustScore < 85).length;
  const flagged = spendings.filter(s => s.trustScore < 50).length;
  const verifiedDocs = spendings.filter(s => s.fileStatus && s.attachId).length;
  const docPercent = totalCount > 0 ? Number(((verifiedDocs / totalCount) * 100).toFixed(1)) : 0;

  const uniqueVendors = new Set(spendings.map(s => String(s.vendorId || s.vendorName))).size;

  return {
    totalSpendingsCount: totalCount,
    totalDisbursedValue: totalValue,
    averageTrustScore: avgTrust,
    highTrustCount: highTrust,
    moderateTrustCount: moderateTrust,
    flaggedCount: flagged,
    verifiedDocumentPercentage: docPercent,
    activeVendorsCount: uniqueVendors
  };
}
